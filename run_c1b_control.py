"""
C1b control experiment.

Purpose: C1 uses GPT-4o-mini for both translation and answer generation.
This script reuses the C1 translations (already generated by run_condition1.py,
stored in results_condition1_200.json) but generates answers with Claude
instead of GPT-4o-mini. If C1b accuracy is close to C1, the C1 accuracy
advantage is mainly due to translation quality, not model self-consistency.
"""

import json
import os
import time
import re
from collections import Counter
from dotenv import load_dotenv
import anthropic
from openai import OpenAI

# Import your existing retrieve() function.
# Adjust this import to match your actual file/module name.
from pipeline import retrieve

load_dotenv()
claude_client = anthropic.Anthropic(api_key=os.getenv("ANTHROPIC_API_KEY"))
openai_client = OpenAI(api_key=os.getenv("OPENAI_API_KEY"))


def build_prompt(question, options, context):
    options_text = "\n".join([f"{k}: {v}" for k, v in options.items()])
    context_text = "\n\n".join(context)
    return f"""You are a medical expert. Use the retrieved context to answer this question and select the correct option.

Retrieved context:
{context_text}

Question: {question}

Options:
{options_text}

Provide a brief explanation and indicate which option is correct."""


def generate_answer_claude(question, options, context):
    """Generate an answer using Claude instead of GPT-4o-mini."""
    prompt = build_prompt(question, options, context)
    response = claude_client.messages.create(
        model="claude-sonnet-4-6",
        max_tokens=300,
        messages=[{"role": "user", "content": prompt}]
    )
    return response.content[0].text


def evaluate_answer(generated_answer, options_zh):
    """Map the generated answer to the closest original Chinese option (A-E),
    using GPT-4o-mini at temperature=0, 3-run majority vote.
    Mirrors the evaluation procedure used for all other conditions."""
    options_text = "\n".join([f"{k}: {v}" for k, v in options_zh.items()])
    prompt = f"""You are given a generated answer to a medical question, and a set of original Chinese options.
Determine which option (A-E) the generated answer corresponds to.

Generated answer: {generated_answer}

Original Chinese options:
{options_text}

Reply with ONLY the single letter (A, B, C, D, or E)."""

    votes = []
    for _ in range(3):
        response = openai_client.chat.completions.create(
            model="gpt-4o-mini",
            messages=[{"role": "user", "content": prompt}],
            max_tokens=5,
            temperature=0
        )
        text = response.choices[0].message.content.strip().upper()
        match = re.search(r'[A-E]', text)
        if match:
            votes.append(match.group())

    if not votes:
        return None
    return Counter(votes).most_common(1)[0][0]


def main():
    # Load C1 results (GPT-4o-mini translations + original generation)
    with open("results_condition1_200.json", "r", encoding="utf-8") as f:
        c1_results = json.load(f)

    # Load original Chinese options (not present in results_condition1_200.json)
    with open("gold_set_200_translated.json", "r", encoding="utf-8") as f:
        gold_data = json.load(f)
    # Build a lookup from id -> original Chinese options
    gold_by_id = {item["id"]: item for item in gold_data}

    print(f"Loaded {len(c1_results)} C1 questions. Running C1b control (Claude generation)...")

    c1b_results = []
    correct_count = 0

    for i, item in enumerate(c1_results):
        # Reuse the C1 (GPT-4o-mini) translation, do NOT re-translate
        question_en = item["question_en_baseline"]
        options_en = item["options_en"]
        gold_answer = item["correct_answer"]

        gold_item = gold_by_id.get(item["id"])
        if gold_item is None:
            print(f"WARNING: no gold data found for id {item['id']}, skipping")
            continue
        options_zh = gold_item["option"]  # adjust this key if different in gold_set_200_translated.json

        # Retrieve using the same retrieval function as the rest of the pipeline
        context = retrieve(question_en, k=3)
        # Generate with Claude instead of GPT-4o-mini
        generated = generate_answer_claude(question_en, options_en, context)

        # Evaluate using the same GPT-4o-mini judge as all other conditions
        selected_option = evaluate_answer(generated, options_zh)

        is_correct = (selected_option == gold_answer)
        if is_correct:
            correct_count += 1

        c1b_results.append({
            "id": item["id"],
            "question_en": question_en,
            "generated_answer_claude": generated,
            "selected_option": selected_option,
            "gold_answer": gold_answer,
            "correct": is_correct
        })

        if (i + 1) % 10 == 0:
            running_acc = correct_count / (i + 1) * 100
            print(f"{i+1}/200 | Running accuracy: {running_acc:.1f}%")

        with open("results_c1b_control.json", "w", encoding="utf-8") as f:
            json.dump(c1b_results, f, ensure_ascii=False, indent=2)

        time.sleep(0.3)

    final_acc = correct_count / len(c1_results) * 100
    print(f"\n=== C1b Control Results ===")
    print(f"Accuracy: {final_acc:.1f}% ({correct_count}/{len(c1_results)})")
    print(f"Compare against original C1 accuracy to assess self-consistency confound.")


if __name__ == "__main__":
    main()